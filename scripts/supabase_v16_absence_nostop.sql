-- ===========================================================================
-- v16: «Временное отсутствие: Без заявки …» не должно останавливать учёт времени.
-- Было: и в коде сайта, и в представлении otp_time_days причина сравнивалась
-- строго со строкой 'Без заявки'. Если к ней добавлялось пояснение
-- («— работа по ЦО»), условие не срабатывало и рабочее время замирало.
-- Здесь правим само представление, не переписывая его целиком: берём текущее
-- определение из каталога, меняем сравнение на сравнение по началу строки.
-- Выполнить один раз в SQL Editor. Идемпотентно.
-- ===========================================================================

do $$
declare
  d text;
begin
  d := pg_get_viewdef('public.otp_time_days'::regclass, true);

  if d is null or d = '' then
    raise notice 'otp_time_days не найдено — пропускаем';
    return;
  end if;

  if d like '%Без заявки%' then
    if d not like '%Без заявки%%' then
      -- '= ''Без заявки''' → 'like ''Без заявки%'''
      d := regexp_replace(d, '=\s*''Без заявки''', 'LIKE ''Без заявки%''', 'g');
      execute 'create or replace view public.otp_time_days as ' || d;
      raise notice 'представление обновлено: сравнение по началу строки';
    else
      raise notice 'уже исправлено ранее';
    end if;
  else
    raise notice 'в представлении нет условия «Без заявки» — ничего не меняем';
  end if;
end $$;

